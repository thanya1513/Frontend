// array methods
let arr = [1, 3, 2, 4, 5];

// push and pop methods
arr.push(6); // push the element to the end
console.log(arr);
console.log(arr.pop());
console.log(arr.pop());

// shift and unshift methods
arr.unshift(5); // adds the element at the starting point
console.log(arr);
arr.shift(); // removes the starting element
console.log(arr);

// sort method
arr.sort();
console.log(arr);

// reverse method
arr.reverse();
console.log(arr);
